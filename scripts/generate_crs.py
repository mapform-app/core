"""Generate src/crs-registry.generated.ts from the official EPSG database shipped with PROJ.

Run with: python3 scripts/generate_crs.py  (requires: pip install pyproj)

The registry is generated, never typed by hand, so every code, name, unit and
projection string matches the EPSG database exactly.
"""

from __future__ import annotations

import json
import warnings
import re
from pathlib import Path

from pyproj import CRS, __proj_version__
from pyproj.database import query_crs_info
from pyproj.enums import PJType

OUT = Path(__file__).resolve().parent.parent / "src" / "crs-registry.generated.ts"

UNIT_MAP = {
    "metre": "m",
    "foot": "ft",
    "US survey foot": "usft",
}

# Projected systems picked explicitly.
EXPLICIT_PROJECTED = [
    2176, 2177, 2178, 2179,  # Poland CS2000 zones 5-8
    2180,                    # Poland CS92
    27700,                   # British National Grid
    3857,                    # Web Mercator (display only)
]
EXPLICIT_PROJECTED += list(range(25828, 25839))  # ETRS89 / UTM 28N-38N
EXPLICIT_PROJECTED += list(range(32601, 32661))  # WGS 84 / UTM north
EXPLICIT_PROJECTED += list(range(32701, 32761))  # WGS 84 / UTM south
EXPLICIT_PROJECTED += list(range(26901, 26924))  # NAD83 / UTM 1N-23N (USGS 3DEP 1 m elevation)
EXPLICIT_PROJECTED += list(range(6330, 6349))    # NAD83(2011) / UTM 59N-19N

# Vertical systems picked explicitly.
EXPLICIT_VERTICAL = [
    9651,  # EVRF2007-PL height
    5703,  # NAVD88 height (m)
    6360,  # NAVD88 height (ftUS)
    5701,  # ODN height
    3855,  # EGM2008 height
]

# All US State Plane systems on NAD83 and NAD83(2011).
STATE_PLANE = re.compile(r"^NAD83(\(2011\))? / [A-Z]")


def with_shift(code: int, proj4: str) -> str:
    shift = TOWGS84.get(code)
    if not shift or "+towgs84" in proj4:
        return proj4
    return proj4.replace(" +units=", f" {shift} +units=", 1)


def unit_of(crs: CRS) -> str | None:
    if not crs.axis_info:
        return None
    return UNIT_MAP.get(crs.axis_info[0].unit_name)


def area_of(crs: CRS) -> str:
    area = crs.area_of_use
    return area.name if area else ""


# Datum shifts to WGS 84 that PROJ strings leave out, where leaving them out moves a point by
# more than a few metres on the map. OSGB36: EPSG transformation 1314 (about 2 m accuracy).
TOWGS84 = {
    27700: "+towgs84=446.448,-125.157,542.06,0.15,0.247,0.842,-20.489",
}


def projected_entry(code: int) -> dict | None:
    crs = CRS.from_epsg(code)
    unit = unit_of(crs)
    if unit is None:
        return None
    return {
        "epsg": code,
        "name": crs.name,
        "kind": "projected",
        "unit": unit,
        "area": area_of(crs),
        "proj4": with_shift(code, crs.to_proj4().replace(" +type=crs", "")),
        "datum": crs.datum.name if crs.datum else None,
        "projection": crs.coordinate_operation.name if crs.coordinate_operation else None,
    }


def vertical_entry(code: int) -> dict | None:
    crs = CRS.from_epsg(code)
    unit = unit_of(crs)
    if unit is None:
        return None
    return {
        "epsg": code,
        "name": crs.name,
        "kind": "vertical",
        "unit": unit,
        "area": area_of(crs),
    }


def main() -> None:
    warnings.simplefilter("ignore", UserWarning)
    codes = set(EXPLICIT_PROJECTED)
    for info in query_crs_info(auth_name="EPSG", pj_types=PJType.PROJECTED_CRS):
        if info.deprecated:
            continue
        if STATE_PLANE.match(info.name):
            codes.add(int(info.code))

    projected = [e for e in (projected_entry(c) for c in sorted(codes)) if e]
    vertical = [e for e in (vertical_entry(c) for c in EXPLICIT_VERTICAL) if e]

    header = (
        "// Generated by scripts/generate_crs.py from the EPSG database in PROJ "
        f"{__proj_version__}. Do not edit by hand.\n"
        "import type { CrsDefinition } from './crs.js';\n\n"
    )
    body = (
        "export const CRS_REGISTRY: readonly CrsDefinition[] = "
        + json.dumps(projected + vertical, ensure_ascii=False, separators=(",", ":"))
        + ";\n"
    )
    OUT.write_text(header + body, encoding="utf-8")
    print(f"Wrote {len(projected)} projected and {len(vertical)} vertical systems to {OUT}")


if __name__ == "__main__":
    main()
